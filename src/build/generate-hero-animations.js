// generate-hero-animations.js
// Node.js script that turns the grid-reveal bitmaps on disk into the two
// hardcoded lists that used to be maintained by hand.
//
// Usage:
//   npm run generate-hero-animations
//
// Reads:  animation/json/grid-*.json
// Writes: blocks/cb-hero/src/animations.js   (editor dropdown options)
//         inc/hero-animations.php            (front-end validation/fallback)
//
// Both outputs are GENERATED and committed, same convention as theme.json
// and src/css/utilities.css — do not hand-edit either one.
//
// Why build-time rather than a runtime glob: animation/json/ only ever
// changes on a dev machine. The deployed theme's bitmaps are fixed, so
// scanning the directory on every editor load and every hero render would be
// paying at runtime for something already known when the theme was built.
//
// The point of generating both ends from one source is that the editor's
// options and the front end's idea of what's valid cannot drift apart. That
// drift is exactly what caused a hero to request a grid-rocket.json that had
// never existed, 404, and silently render nothing.

const fs = require('fs');
const path = require('path');

const themeRoot = path.join(__dirname, '../..');
const jsonDir = path.join(themeRoot, 'animation/json');
const jsOutFile = path.join(themeRoot, 'blocks/cb-hero/src/animations.js');
const phpOutFile = path.join(themeRoot, 'inc/hero-animations.php');

// Used when a hero has no animation set, or names one whose bitmap has since
// been renamed/removed. Must be one of the slugs found below — if it isn't,
// that's a hard error rather than a silent blank hero.
const DEFAULT_ANIMATION = 'bomb';

const BANNER = 'GENERATED by src/build/generate-hero-animations.js — do not hand-edit.';

function findAnimations() {
	if (!fs.existsSync(jsonDir)) {
		throw new Error(`No animation/json directory at ${jsonDir}`);
	}

	return fs
		.readdirSync(jsonDir)
		.filter((f) => f.startsWith('grid-') && f.endsWith('.json'))
		.map((f) => f.slice('grid-'.length, -'.json'.length))
		.sort();
}

function writeJs(slugs) {
	const contents = `// ${BANNER}
// Source of truth is animation/json/grid-*.json.

export const HERO_ANIMATIONS = ${JSON.stringify(slugs, null, '\t').replace(/\n/g, '\n')};

export const DEFAULT_HERO_ANIMATION = ${JSON.stringify(DEFAULT_ANIMATION)};
`;
	fs.writeFileSync(jsOutFile, contents, 'utf8');
}

function writePhp(slugs) {
	const entries = slugs.map((s) => `\t\t${JSON.stringify(s).replace(/"/g, "'")},`).join('\n');
	const contents = `<?php
/**
 * ${BANNER}
 *
 * Source of truth is animation/json/grid-*.json. Read through
 * cb_chillibyte_2026_get_hero_animation_config() rather than requiring this
 * file directly.
 *
 * @package cb-chillibyte-2026
 */

defined( 'ABSPATH' ) || exit;

return array(
\t'available' => array(
${entries}
\t),
\t'default'   => '${DEFAULT_ANIMATION}',
);
`;
	fs.writeFileSync(phpOutFile, contents, 'utf8');
}

const slugs = findAnimations();

if (slugs.length === 0) {
	throw new Error(`No grid-*.json bitmaps found in ${jsonDir}`);
}

if (!slugs.includes(DEFAULT_ANIMATION)) {
	throw new Error(
		`Default animation "${DEFAULT_ANIMATION}" has no animation/json/grid-${DEFAULT_ANIMATION}.json. ` +
			`Found: ${slugs.join(', ')}. Update DEFAULT_ANIMATION in this script or add the missing bitmap.`
	);
}

writeJs(slugs);
writePhp(slugs);

console.log(`Hero animations (${slugs.length}): ${slugs.join(', ')}  [default: ${DEFAULT_ANIMATION}]`);
console.log(`  -> ${path.relative(themeRoot, jsOutFile)}`);
console.log(`  -> ${path.relative(themeRoot, phpOutFile)}`);
